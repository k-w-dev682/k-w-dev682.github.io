import assert from 'node:assert/strict';
import { DEFAULT_DB,validate } from '../src/components/studycenter/engine.js';
import {mergeStudyData,markDeleted,toggleCloudBookmark,addCloudItem,bumpModified} from '../src/components/studycenter/cloud-merge.js';
const base=DEFAULT_DB();
assert.equal(base.syncDeleted.notes.constructor,Object);
const attempt=(id,date,ok)=>({id,subject:'ask',topic:'u2',question:'?',given:'7',answer:'7',why:'',lesson:'u2',ok,mode:'quiz',date,hints:0});
const a={...base,attempts:[attempt('q1',1000000000001,true)],reviews:[{cardId:'c1',rating:'good',date:1000000000001}]};
const b={...base,attempts:[attempt('q2',1000000000002,false)],reviews:[{cardId:'c2',rating:'easy',date:1000000000002}]};
const merged=mergeStudyData(a,b);
assert.equal(merged.attempts.length,2);
assert.equal(merged.reviews.length,2);
assert.deepEqual(mergeStudyData(merged,a,b),merged);
assert.deepEqual(mergeStudyData(a,b),mergeStudyData(b,a));
let c=addCloudItem(base,'notes',{id:'n1',subject:'cpp',text:'zapis',date:1000000000000},1000000000000);
const stale=structuredClone(c);
c=markDeleted(c,'notes','n1',1000000000003);
assert.equal(mergeStudyData(c,stale).notes.length,0);
let d=toggleCloudBookmark(base,'/ask/u2/',1000000000000);
const dStale=structuredClone(d);
d=toggleCloudBookmark(d,'/ask/u2/',1000000000002);
assert.equal(mergeStudyData(d,dStale).bookmarks.length,0);
d=toggleCloudBookmark(d,'/ask/u2/',1000000000004);
assert.equal(mergeStudyData(d,dStale).bookmarks.length,1);
let e=bumpModified({...base,planner:{examDate:'2026-10-25',subject:'ask',minutes:40}},'planner',1000000000002);
let f=bumpModified({...base,planner:{examDate:'2026-10-27',subject:'cpp',minutes:20}},'planner',1000000000005);
assert.equal(mergeStudyData(e,f).planner.examDate,'2026-10-27');
let old=JSON.parse(JSON.stringify(DEFAULT_DB()));delete old.syncDeleted;delete old.syncAdded;delete old.syncModified;
assert.deepEqual(validate(old).syncAdded.bookmarks,{});
console.log('Cloud sync: merge, deletions, bookmarks, settings, legacy migration OK');
